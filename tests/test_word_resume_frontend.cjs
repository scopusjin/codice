const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('app/word_resume_frontend/index.html','utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
const parentMessages=[], topMessages=[];
let handler;
const parent={postMessage:m=>parentMessages.push(m)};
const top={postMessage:m=>topMessages.push(m)};
vm.runInNewContext(script,{parent,top,addEventListener:(_,f)=>{handler=f;}});
handler({source:parent,data:{type:'streamlit:render',args:{token:'a'.repeat(32)}}});
assert.equal(topMessages[0].type,'mortem:resume-request');
handler({source:{},data:{type:'mortem:resume-data',token:'a'.repeat(32),data:'payload'}});
handler({source:top,data:{type:'mortem:resume-data',token:'b'.repeat(32),data:'payload'}});
assert.equal(parentMessages.filter(m=>m.type==='streamlit:setComponentValue').length,0);
handler({source:top,data:{type:'mortem:resume-data',token:'a'.repeat(32),data:'payload'}});
handler({source:top,data:{type:'mortem:resume-data',token:'a'.repeat(32),data:'payload'}});
assert.equal(parentMessages.filter(m=>m.type==='streamlit:setComponentValue').length,1);
console.log('Word resume frontend: source/token validation and single delivery passed.');
